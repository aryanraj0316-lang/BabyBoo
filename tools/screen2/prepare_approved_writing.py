"""Register approved artwork and local repair patches without recolouring."""
from pathlib import Path
import json
import shutil
import sys
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools/buddy'))
from normalize import place
OUT=ROOT/'design/screen2/approved_writing';OUT.mkdir(exist_ok=True)
ASSETS=ROOT/'assets/onboarding/screen2/buddy'
m=json.loads((ROOT/'design/screen2/localized_note/manifest.json').read_text())['registration']
k=106/m['head_w']
def pt(x,y):return [round(80+(x-m['seat_cx'])*k,4),round(155+(y-m['baseline'])*k,4)]
def svg(commands):
    result=[]
    for command,coords in commands:
        result.append(command)
        for i in range(0,len(coords),2):result.extend(str(v) for v in pt(*coords[i:i+2]))
    return ' '.join(result)
paw=svg([('M',[330,758]),('C',[299,765,279,799,273,847]),('C',[265,889,280,935,317,952]),('C',[368,980,456,972,495,936]),('C',[528,907,520,865,490,842]),('C',[463,817,430,807,393,794]),('C',[365,784,345,773,330,758]),('Z',[])])
pen=svg([('M',[414,748]),('C',[430,738,449,754,458,770]),('L',[560,929]),('L',[551,942]),('L',[531,927]),('L',[410,782]),('Z',[])])
eye_rects=[]
for x,y,w,h in [(431,393,135,139),(787,475,130,138)]:
    px,py=pt(x,y);eye_rects.append({'x':px,'y':py,'width':round(w*k,4),'height':round(h*k,4)})
tip=pt(555,934);cap=pt(429,755)
pen_source=Image.open(ROOT/'design/buddy/generated/buddy_screen2_writing_pen-original.png').convert('RGBA')
alpha=np.array(pen_source.getchannel('A'))
pen_source=pen_source.crop(Image.fromarray(np.uint8(alpha>8)*255).getbbox())
metrics={'tip':tip,'penHeight':round(float(np.hypot(tip[0]-cap[0],tip[1]-cap[1])),4),
 'penAngle':round(float(-np.arctan2(tip[0]-cap[0],tip[1]-cap[1])),5),
 'pawPath':paw,'repairPath':paw+' '+pen,'penRepairPath':pen,'pawOrigin':pt(300,815),'eyeRects':eye_rects,
 'card':[pt(*p) for p in [(436,906),(733,873),(742,1002),(460,1042)]],
 'strokes':[[[round(tip[0]+dx,4),round(tip[1]+dy,4)] for dx,dy in [(0,0),(.7,-.7),(1.4,.1),(2.1,-1),(2.8,-.2),(3.5,-1.3),(4.2,-.5),(4.9,-1.5),(5.6,-.7),(6.3,-1.7),(7,-.9)]]]}
for density in (2,3):
    shutil.copyfile(ROOT/f'design/screen2/localized_note/candidate@{density}x.webp',ASSETS/f'buddy_note_approved@{density}x.webp')
    pen_size=(round(36*density*pen_source.width/pen_source.height),36*density)
    pen_source.convert('RGBa').resize(pen_size,Image.Resampling.LANCZOS).convert('RGBA').save(
        ASSETS/f'buddy_note_pen@{density}x.webp','WEBP',quality=94,method=6)
    for key,source in [('repair','buddy_screen2_approved_writing_repair-original.png'),('penless','buddy_screen2_approved_penless-original.png')]:
        rgba=np.array(Image.open(ROOT/'design/buddy/generated'/source).convert('RGBA'))
        placed=place(rgba,m,False,k*density,(160*density,159*density),155*density)
        placed.save(ASSETS/f'buddy_note_{key}@{density}x.webp','WEBP',quality=94,method=6)
(OUT/'registration.json').write_text(json.dumps(metrics,indent=2))
(ROOT/'src/onboarding/screen2/noteRegistration.generated.ts').write_text('/** Approved pose registration; generated by prepare_approved_writing.py. */\nexport const noteRegistration = '+json.dumps(metrics,indent=2)+' as const;\n')
print(json.dumps({'tip':tip,'penHeight':metrics['penHeight'],'penAngle':metrics['penAngle']}))
